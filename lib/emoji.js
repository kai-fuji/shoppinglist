// 長いキーワードほど先に判定されるようソート
const SORTED_KEYWORDS = Object.entries(KEYWORD_EMOJI).sort(
  (a, b) => b[0].length - a[0].length
)

export const itemEmoji = (category, name = '') => {
  const n = (name || '').trim()
  if (n) {
    for (const [keyword, emoji] of SORTED_KEYWORDS) {
      if (n.includes(keyword)) return emoji
    }
  }
  return CATEGORY_EMOJI[category] || '🛒'
}